#!/usr/bin/env python3
"""Remove build-path bytecode/provenance from an explicit disposable engine copy.

This never cleans an installed app or live library, removes no keys/databases,
and does not establish runtime or minimum-OS compatibility.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile

PROVENANCE = {
    'engine-manifest.json', 'runtime-sources.json', 'runtime-target.json',
    'runtime-relocations.json', 'tool-manifest.json', 'tool-relocation-test.json',
    'tool-ocr-relocation-test.json', 'runtime-audit.json', 'bundle-audit.json',
}
RECEIPT = 'runtime-cleanup.json'
URI = re.compile(r'^[A-Za-z][A-Za-z0-9+.-]*:')
DISTLIB = Path('python/lib/python3.11/site-packages/pip/_vendor/distlib')
WINDOWS_LAUNCHERS = ('t32.exe', 'w32.exe', 't64.exe', 'w64.exe', 't64-arm.exe', 'w64-arm.exe')
SETUPTOOLS = Path('python/lib/python3.11/site-packages/setuptools')
SETUPTOOLS_LAUNCHERS = ('cli.exe', 'cli-32.exe', 'cli-64.exe', 'cli-arm64.exe', 'gui.exe', 'gui-32.exe', 'gui-64.exe', 'gui-arm64.exe')
# This upstream Torch fixture intentionally contains Python 3.12-only syntax.
# Keep its source unchanged; it is not imported by the Python 3.11 runtime path.
UNCOMPILED_SOURCE_FIXTURES = {
    'python/lib/python3.11/site-packages/torch/testing/_internal/py312_intrinsics.py': 'Upstream Python 3.12 syntax fixture',
}


def require_embedded_compiler(root: Path):
    interpreter = root / 'python/bin/python3.11'
    if sys.version_info[:2] != (3, 11) or not interpreter.is_file() or interpreter.resolve() != Path(sys.executable).resolve():
        raise ValueError('Run --compile-bytecode with this bundle\'s python/bin/python3.11; host Python bytecode is not accepted.')


def compile_bytecode(root: Path, sources: list[Path], markers: list[bytes]) -> int:
    import compileall
    import marshal
    import py_compile
    import types
    require_embedded_compiler(root)
    # Disable incidental import caches. Explicit compileall writes checked-hash
    # caches whose logical source names are independent of the builder's home.
    sys.dont_write_bytecode = True
    excluded = re.compile('^(?:' + '|'.join(re.escape(str(root / path)) for path in UNCOMPILED_SOURCE_FIXTURES) + ')$')
    for name in ['python', 'engine']:
        if not compileall.compile_dir(str(root / name), ddir=f'/CliptextRuntime/{name}', force=True,
                                     quiet=1, workers=min(4, os.cpu_count() or 1), optimize=0,
                                     rx=excluded,
                                     invalidation_mode=py_compile.PycInvalidationMode.CHECKED_HASH,
                                     limit_sl_dest=str(root)):
            raise ValueError(f'Logical bytecode compilation failed for {name}.')
    def verify_code(code, expected):
        if not isinstance(code, types.CodeType) or code.co_filename != expected:
            raise ValueError('Generated bytecode has an unexpected source filename.')
        for value in code.co_consts:
            if isinstance(value, types.CodeType): verify_code(value, expected)
    for source in sources:
        path = Path(importlib.util.cache_from_source(str(source), optimization=''))
        payload = path.read_bytes()
        if payload[:4] != importlib.util.MAGIC_NUMBER or int.from_bytes(payload[4:8], 'little') != 3 or payload[8:16] != importlib.util.source_hash(source.read_bytes()):
            raise ValueError('Generated bytecode has an incorrect interpreter/header/source hash.')
        if any(marker in payload for marker in markers):
            raise ValueError('Generated bytecode contains builder path markers.')
        verify_code(marshal.loads(payload[16:]), '/CliptextRuntime/' + source.relative_to(root).as_posix())
    return len(sources)


def inside(path: Path, root: Path) -> bool:
    return path == root or root in path.parents


def atomic_json(path: Path, value, mode=0o600):
    descriptor, temporary = tempfile.mkstemp(prefix='.cliptext-clean-', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'w') as stream:
            json.dump(value, stream, indent=2, ensure_ascii=False)
            stream.write('\n')
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def source_for_bytecode(path: Path) -> Path:
    if path.parent.name == '__pycache__':
        try:
            return Path(importlib.util.source_from_cache(str(path)))
        except ValueError:
            # An unrecognized cache name is orphaned, never guessed/deleted.
            return path.with_name(path.name + '.no-corresponding-source')
    return path.with_suffix('.py')


def clean_runtime(bundle: Path, builder_home: Path | None = None, compile_caches: bool = False) -> dict:
    supplied = bundle.absolute()
    root = bundle.resolve(strict=True)
    home = (builder_home or Path.home()).resolve(strict=False)
    if not home.is_absolute() or len(home.parts) < 3 or len(home.name) < 2:
        raise ValueError('Use a complete builder home directory.')
    if any(part.lower().endswith('.app') for part in (*supplied.parts, *root.parts)):
        raise ValueError('Refusing to clean inside an installed application bundle.')
    if inside(root, home / 'Library') or inside(root, Path.home().resolve(strict=False) / 'Library'):
        raise ValueError('Refusing to clean a live Library directory; use a disposable build copy.')
    if not root.is_dir() or supplied.is_symlink():
        raise ValueError('The bundle must be a regular disposable engine directory.')
    for name in ['engine', 'python', 'resources']:
        directory = root / name
        if not directory.is_dir() or directory.is_symlink() or not inside(directory.resolve(), root):
            raise ValueError('The engine copy must contain regular engine, python and resources directories.')
    manifest_path = root / 'resources' / 'engine-manifest.json'
    manifest = json.loads(manifest_path.read_text())
    if manifest_path.is_symlink() or not isinstance(manifest, dict) or manifest.get('format') != 'cliptext-local-engine':
        raise ValueError('The bundle is not a managed cliptext-local-engine copy.')
    if compile_caches:
        require_embedded_compiler(root)
    markers = [str(home), home.name]
    byte_markers = [marker.encode('utf-8') for marker in markers]
    files, caches = [], []
    for directory, names, entries in os.walk(root, followlinks=False):
        parent = Path(directory)
        names[:] = [name for name in names if not (parent / name).is_symlink()]
        if parent.name == '__pycache__':
            caches.append(parent)
        files.extend(parent / name for name in entries if not (parent / name).is_symlink())
    removed, orphans, windows_launchers = [], [], []
    updates = []
    substitutions = 0

    # Pip vendors Windows console launchers even in the macOS wheel. Only these
    # inert, upstream pip/setuptools assets may be pruned; every other foreign
    # executable remains for the separate native-payload gate to reject.
    for parent, name in [(DISTLIB, name) for name in WINDOWS_LAUNCHERS] + [(SETUPTOOLS, name) for name in SETUPTOOLS_LAUNCHERS]:
        path = root / parent / name
        if not path.exists() and not path.is_symlink():
            continue
        if path.is_symlink() or not stat.S_ISREG(path.stat().st_mode) or any(parent.is_symlink() for parent in path.parents if inside(parent, root)):
            raise ValueError(f'Upstream Windows launcher is not a regular staged file: {path.relative_to(root).as_posix()}')
        with path.open('rb') as stream:
            if stream.read(2) != b'MZ':
                raise ValueError(f'Upstream launcher does not have its expected Windows header: {path.relative_to(root).as_posix()}')
        windows_launchers.append(path)

    def has_marker(value: str) -> bool:
        return any(marker in value for marker in markers)

    def sanitize(value):
        nonlocal substitutions
        if isinstance(value, str):
            if str(home) in value and not URI.match(value):
                substitutions += value.count(str(home))
                return value.replace(str(home), '<build-home>')
            return value
        if isinstance(value, list):
            return [sanitize(item) for item in value]
        if isinstance(value, dict):
            return {key: sanitize(item) for key, item in value.items()}
        return value

    def metadata_has_marker(value) -> bool:
        if isinstance(value, str):
            return has_marker(value)
        if isinstance(value, list):
            return any(metadata_has_marker(item) for item in value)
        if isinstance(value, dict):
            return any(has_marker(key) or metadata_has_marker(item) for key, item in value.items())
        return False

    # Plan everything first: refusal must not leave a partially cleaned copy.
    for path in sorted(files):
        relative = path.relative_to(root).as_posix()
        if path.suffix == '.pyc':
            source = source_for_bytecode(path)
            if source.is_file() and not source.is_symlink() and inside(source.resolve(), root):
                removed.append(path)
            else:
                payload = path.read_bytes()
                if any(marker in payload for marker in byte_markers):
                    raise ValueError(f'Orphan bytecode contains builder path markers: {relative}')
                orphans.append(relative)
        if path.suffix.lower() != '.json' or relative == f'resources/{RECEIPT}':
            continue
        value = json.loads(path.read_text())
        parts = path.relative_to(root).parts
        tool_receipt = path.name == 'build-receipt.json' and parts[:2] == ('licenses', 'tools')
        brew_receipt = path.name == 'INSTALL_RECEIPT.json' and 'licenses' in parts[:-1]
        allowed = (path.parent == root / 'resources' and path.name in PROVENANCE) or tool_receipt or brew_receipt
        original = json.dumps(value, ensure_ascii=False)
        if allowed:
            # Homebrew's local formula source location is not a source URI and
            # has no recipient value. Preserve its public URL/hash/version data.
            if (tool_receipt or brew_receipt) and isinstance(value, dict) and isinstance(value.get('source'), dict):
                location = value['source'].get('path')
                if isinstance(location, str) and str(home) in location and not URI.match(location):
                    del value['source']['path']
                    substitutions += 1
            value = sanitize(value)
        if metadata_has_marker(value):
            raise ValueError(f'Builder markers remain in metadata; review explicitly: {relative}')
        if json.dumps(value, ensure_ascii=False) != original:
            updates.append((path, value, stat.S_IMODE(path.stat().st_mode)))
    if any(has_marker(path.relative_to(root).as_posix()) for path in [*removed, *windows_launchers, *caches, *(path for path, _, _ in updates)]) or any(has_marker(path) for path in orphans):
        raise ValueError('A cleanup receipt would contain builder markers in a relative filename; review explicitly.')
    for path in [*removed, *windows_launchers]:
        path.unlink()
    empty = []
    for path in sorted(caches, key=lambda item: len(item.parts), reverse=True):
        if not any(path.iterdir()):
            path.rmdir()
            empty.append(path.relative_to(root).as_posix())
    for path, value, mode in updates:
        atomic_json(path, value, mode)
    excluded_sources = [{'path': path.relative_to(root).as_posix(), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                         'reason': UNCOMPILED_SOURCE_FIXTURES[path.relative_to(root).as_posix()]} for path in files if path.relative_to(root).as_posix() in UNCOMPILED_SOURCE_FIXTURES]
    compiled = compile_bytecode(root, [path for path in files if path.suffix == '.py' and path.relative_to(root).parts[0] in {'python', 'engine'} and path.relative_to(root).as_posix() not in UNCOMPILED_SOURCE_FIXTURES], byte_markers) if compile_caches else 0
    receipt = {
        'format': 'cliptext-runtime-cleanup', 'version': 1,
        'removedBytecodeCount': len(removed),
        'removedBytecodePaths': [path.relative_to(root).as_posix() for path in removed],
        'removedWindowsLauncherCount': len(windows_launchers),
        'removedWindowsLauncherPaths': [path.relative_to(root).as_posix() for path in windows_launchers],
        'removedEmptyCacheDirectories': empty,
        'retainedOrphanBytecode': [{'path': name, 'builderPathMarkersAbsent': True} for name in orphans],
        'sanitizedMetadataFiles': [path.relative_to(root).as_posix() for path, _, _ in updates],
        'provenanceSubstitutions': substitutions,
        'metadataBuilderMarkersAbsent': True,
        'compiledBytecodeCount': compiled,
        'bytecodeCompiler': 'cp311' if compile_caches else None,
        'compiledBytecodeVerified': compile_caches,
        'uncompiledSourceFixtures': excluded_sources if compile_caches else [],
    }
    atomic_json(root / 'resources' / RECEIPT, receipt)
    return receipt


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle', type=Path, required=True, help='Disposable managed engine copy; never an installed .app or live library.')
    parser.add_argument('--builder-home', type=Path, help='Builder home marker (default: current user home).')
    parser.add_argument('--compile-bytecode', action='store_true', help='Regenerate verified logical-path caches; invoke with this bundle\'s Python 3.11.')
    args = parser.parse_args(argv)
    try:
        result = clean_runtime(args.bundle, args.builder_home, args.compile_bytecode)
    except (ValueError, OSError, json.JSONDecodeError) as error:
        parser.exit(1, f'Runtime cleanup refused: {error}\n')
    print(json.dumps({key: result[key] for key in ['format', 'removedBytecodeCount', 'removedWindowsLauncherCount', 'compiledBytecodeCount', 'provenanceSubstitutions', 'metadataBuilderMarkersAbsent']}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
